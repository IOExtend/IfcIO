"""Generate the product occurrence index from official buildingSMART EXPRESS files.

Usage: python tools/generate_product_occurrences.py IFC2X3_TC1.exp IFC4_ADD2_TC1.exp IFC4X3_ADD2.exp
The schema files are inputs only and are not distributed in the repository.
"""

import argparse
import re
from pathlib import Path


def product_occurrences(path, expected_schema):
    schema = re.sub(r"\(\*.*?\*\)|--[^\n]*", "", path.read_text(encoding="utf-8-sig"), flags=re.S)
    if not re.search(rf"(?im)^SCHEMA\s+{expected_schema}\s*;", schema):
        raise ValueError(f"{path}: expected SCHEMA {expected_schema}")

    entities = {}
    for entity, header in re.findall(r"(?im)^ENTITY\s+(\w+)\b([^;]*);", schema):
        parents = re.search(r"\bSUBTYPE\s+OF\s*\(([^)]*)\)", header, re.I)
        parent = parents[1].strip().upper() if parents else None
        if parent and not parent.isidentifier():
            raise ValueError(f"{path}: unsupported supertype declaration for {entity}")
        entities[entity.upper()] = (parent, bool(re.search(r"\bABSTRACT\b", header, re.I)))

    def ancestry(name):
        while name:
            yield name
            name, _ = entities[name]

    excluded = {"IFCSPATIALELEMENT", "IFCSPATIALSTRUCTUREELEMENT", "IFCPORT"}
    for name, (_, abstract) in entities.items():
        lineage = set(ancestry(name))
        if abstract or "IFCPRODUCT" not in lineage or (lineage & excluded and name != "IFCSITE"):
            continue
        tag_index = 7 if "IFCELEMENT" in lineage else 8 if name == "IFCPROXY" else -1
        yield name, tag_index, "IFCFEATUREELEMENTSUBTRACTION" in lineage


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("ifc2x3", type=Path)
    parser.add_argument("ifc4", type=Path)
    parser.add_argument("ifc4x3", type=Path)
    args = parser.parse_args()

    by_name = {}
    for path, schema, mask in (
        (args.ifc2x3, "IFC2X3", "V2x3"),
        (args.ifc4, "IFC4", "V4"),
        (args.ifc4x3, "IFC4X3_ADD2", "V4x3"),
    ):
        for name, tag_index, subtracts in product_occurrences(path, schema):
            entry = by_name.setdefault(name, ([], tag_index, subtracts))
            if entry[1:] != (tag_index, subtracts):
                raise ValueError(f"{name}: occurrence metadata changes between schemas")
            entry[0].append(mask)

    output = [
        "// Generated by tools/generate_product_occurrences.py from buildingSMART IFC2x3 TC1, IFC4 ADD2 TC1 and IFC4.3 ADD2.",
        "using System.Collections.Frozen;",
        "",
        "namespace IfcIO.Schema;",
        "",
        "internal static class IfcProductOccurrences",
        "{",
        "    private const int V2x3 = 1, V4 = 2, V4x3 = 4;",
        "",
        "    public static bool TryGetInfo(IfcSchema schema, string type, out int tagIndex, out bool subtracts)",
        "    {",
        "        tagIndex = -1;",
        "        subtracts = false;",
        "        int version = schema switch",
        "        {",
        "            IfcSchema.Ifc2x3 => V2x3,",
        "            IfcSchema.Ifc4 => V4,",
        "            IfcSchema.Ifc4x3 => V4x3,",
        "            _ => 0,",
        "        };",
        "        if (!Types.TryGetValue(type, out var occurrence) || (occurrence.Versions & version) == 0) return false;",
        "        tagIndex = occurrence.TagIndex;",
        "        subtracts = occurrence.Subtracts;",
        "        return true;",
        "    }",
        "",
        "    private static readonly FrozenDictionary<string, (int Versions, int TagIndex, bool Subtracts)> Types =",
        "        new Dictionary<string, (int, int, bool)>(StringComparer.OrdinalIgnoreCase)",
        "        {",
    ]
    for name, (versions, tag_index, subtracts) in sorted(by_name.items()):
        output.append(f'            ["{name}"] = ({" | ".join(versions)}, {tag_index}, {str(subtracts).lower()}),')
    output += ["        }.ToFrozenDictionary(StringComparer.OrdinalIgnoreCase);", "}", ""]
    destination = Path(__file__).resolve().parents[1] / "src" / "IfcIO" / "Schema" / "IfcProductOccurrences.g.cs"
    destination.write_text("\n".join(output), encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
